#!/usr/bin/env python3
"""
Generate SAMPLE Windows Security logon events for the Log Analyzer demo.

The data is synthetic: fictional accounts, a fictional "LAB" domain and
IP addresses from the RFC 5737 documentation ranges (192.0.2.0/24,
198.51.100.0/24, 203.0.113.0/24) plus private 10.x addresses.

The CSV uses the same columns that Export-LogonEvents.ps1 produces from a
real Windows host, so real exports can be analyzed the same way.

Scenarios included (so every detection rule has something to find):
  * normal successful logons and a few one-off typos (background noise)
  * a fast brute-force burst against "administrator" over RDP/NLA
  * a password spray across many accounts, including non-existent ones
  * a brute-force burst that ends in a successful logon (svc_backup)
  * a user who locks themselves out with typos (4740 lockout)
  * an attempt against a disabled account

Usage: python3 generate_sample.py > sample-security-events.csv
"""
import csv
import random
import sys
from datetime import datetime, timedelta

random.seed(4625)  # deterministic output
DAY = datetime(2026, 10, 20)
DOMAIN = "LAB"
USERS = ["jdoe", "mlee", "kpatel", "rgarcia", "tnguyen", "swilson", "bchen", "ojohnson", "dlopez", "ewright"]
WORKSTATIONS = ["WS-0141", "WS-0172", "WS-0203", "LT-0310", "LT-0322", "LT-0347"]
COLUMNS = ["TimeCreated", "EventID", "TargetUserName", "TargetDomainName", "IpAddress",
           "LogonType", "Status", "SubStatus", "WorkstationName"]

rows = []


def add(ts, event_id, user, ip="-", logon_type="", status="", sub="", ws="-"):
    rows.append({
        "TimeCreated": ts.strftime("%Y-%m-%dT%H:%M:%S.") + f"{ts.microsecond // 1000:03d}Z",
        "EventID": event_id, "TargetUserName": user, "TargetDomainName": DOMAIN,
        "IpAddress": ip, "LogonType": logon_type, "Status": status, "SubStatus": sub, "WorkstationName": ws,
    })


def at(h, m, s=0):
    return DAY + timedelta(hours=h, minutes=m, seconds=s, milliseconds=random.randint(0, 999))


# 1) Background: normal workday logons + occasional single typos.
for _ in range(70):
    user = random.choice(USERS)
    ts = at(random.randint(7, 18), random.randint(0, 59), random.randint(0, 59))
    ip = f"10.10.{random.choice([20, 21, 30])}.{random.randint(10, 250)}"
    add(ts, 4624, user, ip, random.choice([2, 3, 3, 3, 10]), ws=random.choice(WORKSTATIONS))
for _ in range(14):
    user = random.choice(USERS)
    ts = at(random.randint(7, 18), random.randint(0, 59), random.randint(0, 59))
    ip = f"10.10.{random.choice([20, 21])}.{random.randint(10, 250)}"
    add(ts, 4625, user, ip, random.choice([2, 3]), "0xC000006D", "0xC000006A", random.choice(WORKSTATIONS))
    add(ts + timedelta(seconds=random.randint(8, 40)), 4624, user, ip, 2, ws=random.choice(WORKSTATIONS))

# 2) Brute force: 60 failures against administrator in about 6 minutes (RDP with NLA logs type 3).
start = at(1, 12)
for i in range(60):
    add(start + timedelta(seconds=i * 6 + random.randint(0, 3)), 4625, "administrator",
        "203.0.113.45", 3, "0xC000006D", "0xC000006A", "kali")

# 3) Password spray: 1 to 2 tries per account, many accounts, slow pace, some names do not exist.
spray_targets = USERS + ["admin", "test", "backup", "helpdesk", "scanner", "guest", "sql", "training",
                         "reception", "itadmin", "print", "user1", "support", "ftp", "web"]
start = at(3, 40)
for i, user in enumerate(spray_targets):
    exists = user in USERS or user == "guest"
    sub = "0xC000006A" if exists else "0xC0000064"
    if user == "guest":
        sub = "0xC0000072"  # account disabled
    for k in range(1 if i % 3 else 2):
        add(start + timedelta(seconds=i * 48 + k * 5), 4625, user, "198.51.100.23", 3, "0xC000006D", sub, "-")

# 4) Brute force that succeeds: svc_backup, 18 failures then a 4624.
start = at(14, 5)
for i in range(18):
    add(start + timedelta(seconds=i * 13), 4625, "svc_backup", "192.0.2.77", 3, "0xC000006D", "0xC000006A", "-")
add(start + timedelta(seconds=18 * 13 + 9), 4624, "svc_backup", "192.0.2.77", 3, ws="-")

# 5) A user who locks themselves out (5 typos) followed by a 4740 lockout event.
start = at(9, 27)
for i in range(5):
    add(start + timedelta(seconds=i * 20), 4625, "mlee", "10.10.20.15", 2, "0xC000006D", "0xC000006A", "WS-0172")
add(start + timedelta(seconds=105), 4740, "mlee", ws="WS-0172")

rows.sort(key=lambda r: r["TimeCreated"])
out = csv.DictWriter(sys.stdout, fieldnames=COLUMNS, quoting=csv.QUOTE_ALL, lineterminator="\n")
sys.stdout.write("# SAMPLE DATA: synthetic events generated by generate_sample.py for demo purposes only.\n")
out.writeheader()
out.writerows(rows)
